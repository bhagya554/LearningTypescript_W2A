let browsser = "safari"
switch (browsser) {
    case "chrome":
        console.log("Chrome browser launched")
        break;
    case "firefox":
        console.log("Firefox browser launched")
        break;
    case "safari":
        console.log("Safari browser launched")
        break;
    case "edge":
        console.log("Edge browser launched")
        break;
    default:
        console.log("Not valid browser")
}